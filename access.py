# array[index]1D,arr[row,colomn]2D,arr[depth,row,column]3D
import numpy as np
array1D = np.array([1, 2, 3, 4, 5])
print(array1D[0])  # Accessing the first element of the 1D
print(array1D[2])  # Accessing the third element of the 1D array
print(array1D[-1])  # Accessing the last element of the 1D array
